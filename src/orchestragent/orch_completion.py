"""`orch completion bash|zsh|fish`: shell completion generated from the real CLI parser.

Generated, not hand-written, so it always matches the commands and flags `orch` accepts.
Install (macOS's default shell is zsh):
    orch completion zsh > "${fpath[1]}/_orch"        # then: autoload -U compinit && compinit
    orch completion bash > ~/.local/share/bash-completion/completions/orch
    orch completion fish > ~/.config/fish/completions/orch.fish
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass, field

SHELLS = ("bash", "zsh", "fish")


@dataclass
class Command:
    name: str
    help: str
    flags: list[tuple[str, str, list[str]]] = field(default_factory=list)  # flag, help, choices


def commands(parser: argparse.ArgumentParser) -> tuple[list[tuple[str, str, list[str]]],
                                                        list[Command]]:
    """Global flags and each subcommand's flags (with fixed choices), in parser order."""
    def flags_of(p: argparse.ArgumentParser) -> list[tuple[str, str, list[str]]]:
        found = []
        for action in p._actions:  # argparse exposes no public iterator over its actions
            if not action.option_strings or isinstance(action, argparse._HelpAction):
                continue
            help_text = "" if action.help == argparse.SUPPRESS else (action.help or "")
            if action.help == argparse.SUPPRESS:
                continue
            choices = [str(c) for c in action.choices] if action.choices else []
            for flag in action.option_strings:
                if flag.startswith("--"):
                    found.append((flag, help_text, choices))
        return found

    subs: list[Command] = []
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            helps = {choice.dest: choice.help or "" for choice in action._choices_actions}
            for name, sub in action.choices.items():
                subs.append(Command(name, helps.get(name, ""), flags_of(sub)))
    return flags_of(parser), subs


def _clean(text: str) -> str:
    return " ".join(text.replace("'", "").replace('"', "").replace(":", " -").split())[:70]


def bash(parser: argparse.ArgumentParser) -> str:
    globals_, subs = commands(parser)
    cases = "\n".join(
        f"        {cmd.name}) opts=\"{' '.join(f for f, _, _ in cmd.flags)}\" ;;" for cmd in subs)
    choices = "\n".join(
        f"        {flag}) COMPREPLY=($(compgen -W \"{' '.join(values)}\" -- \"$cur\")); return ;;"
        for flag, values in sorted({f: c for cmd in subs for f, _, c in cmd.flags if c}.items()))
    top = " ".join([*(c.name for c in subs), *(f for f, _, _ in globals_)])
    return f"""# bash completion for orch (generated by `orch completion bash`)
_orch() {{
    local cur prev cmd i opts
    cur="${{COMP_WORDS[COMP_CWORD]}}"
    prev="${{COMP_WORDS[COMP_CWORD-1]}}"
    case "$prev" in
{choices}
    esac
    cmd=""
    for ((i = 1; i < COMP_CWORD; i++)); do
        case "${{COMP_WORDS[i]}}" in -*) ;; *) cmd="${{COMP_WORDS[i]}}"; break ;; esac
    done
    if [ -z "$cmd" ]; then
        COMPREPLY=($(compgen -W "{top}" -- "$cur"))
        return
    fi
    opts=""
    case "$cmd" in
{cases}
    esac
    COMPREPLY=($(compgen -W "$opts" -o default -- "$cur"))
}}
complete -o default -F _orch orch
"""


def zsh(parser: argparse.ArgumentParser) -> str:
    globals_, subs = commands(parser)
    listed = "\n".join(f"        '{cmd.name}:{_clean(cmd.help)}'" for cmd in subs)

    def spec(flags: list[tuple[str, str, list[str]]]) -> str:
        lines = []
        for flag, help_text, choices in flags:
            values = f":value:({' '.join(choices)})" if choices else ""
            lines.append(f"            '{flag}[{_clean(help_text)}]{values}'")
        return " \\\n".join(lines)

    cases = "\n".join(
        f"        {cmd.name})\n            _arguments \\\n{spec(cmd.flags)}"
        f"{' ' + chr(92) + chr(10) if cmd.flags else ''}            '*:file:_files' ;;"
        for cmd in subs)
    return f"""#compdef orch
# zsh completion for orch (generated by `orch completion zsh`)
_orch() {{
    local -a subcommands
    subcommands=(
{listed}
    )
    _arguments -C \\
{spec(globals_)} \\
        '1: :->command' \\
        '*:: :->args'
    case $state in
        command) _describe -t commands 'orch command' subcommands ;;
        args)
            case $words[1] in
{cases}
            esac ;;
    esac
}}
_orch "$@"
"""


def fish(parser: argparse.ArgumentParser) -> str:
    globals_, subs = commands(parser)
    names = " ".join(cmd.name for cmd in subs)
    lines = ["# fish completion for orch (generated by `orch completion fish`)",
             "complete -c orch -f"]
    for cmd in subs:
        lines.append(f"complete -c orch -n 'not __fish_seen_subcommand_from {names}' "
                     f"-a {cmd.name} -d '{_clean(cmd.help)}'")
    for flag, help_text, _ in globals_:
        lines.append(f"complete -c orch -l {flag[2:]} -d '{_clean(help_text)}'")
    for cmd in subs:
        for flag, help_text, choices in cmd.flags:
            values = f" -x -a '{' '.join(choices)}'" if choices else ""
            lines.append(f"complete -c orch -n '__fish_seen_subcommand_from {cmd.name}' "
                         f"-l {flag[2:]} -d '{_clean(help_text)}'{values}")
    return "\n".join(lines) + "\n"


def render(shell: str, parser: argparse.ArgumentParser) -> str:
    if shell not in SHELLS:
        raise ValueError(f"shell must be one of {', '.join(SHELLS)}")
    return {"bash": bash, "zsh": zsh, "fish": fish}[shell](parser)
